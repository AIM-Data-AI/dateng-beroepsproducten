"""
voorbeeld_inlezen_api.py
=========================
Fetches data from a public JSON API using the requests module, turns the
JSON response into a Python data structure (a list of dicts), and then
turns that into SQL INSERT statements.

API: JSONPlaceholder (https://jsonplaceholder.typicode.com/posts). No API
key needed. The endpoint GET /posts?userId=<id> returns a JSON array with
that user's posts.

Steps:
  1. Call the API once for every user_id in USER_IDS (one GET request per
     id, with the id passed as a query parameter).
  2. Combine the JSON arrays from all calls into a single list of dicts.
  3. Turn that list into batched INSERT INTO posts (...) VALUES (...)
     statements and write them to a .sql file.

Usage:
    python voorbeeld_inlezen_api.py
    python voorbeeld_inlezen_api.py --user-ids 1 2   # fetch only these users, for testing
"""

import argparse
import os

import requests

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_PATH = os.path.join(SCRIPT_DIR, "dml_posts_voorbeeld.sql")
API_URL = "https://jsonplaceholder.typicode.com/posts"
REQUEST_TIMEOUT = 30
USER_IDS = list(range(1, 11))  # JSONPlaceholder has users 1-10
BATCH_SIZE = 100  # rows per INSERT statement


def fetch_posts(user_id: int) -> list[dict]:
    """Fetches all posts for one user_id. Returns a list of dicts, e.g.
    {"userId": 1, "id": 1, "title": "...", "body": "..."}."""
    response = requests.get(
        API_URL,
        params={"userId": user_id},
        timeout=REQUEST_TIMEOUT,
    )
    response.raise_for_status()
    return response.json()


def fetch_all(user_ids: list[int]) -> list[dict]:
    """Fetches posts for each user_id in turn and combines them into a
    single list, printing per-user counts as it goes."""
    combined: list[dict] = []
    for user_id in user_ids:
        posts = fetch_posts(user_id)
        print(f"user {user_id}: {len(posts)} posts")
        combined.extend(posts)
    return combined


def sql_string(value: str) -> str:
    """Escapes single quotes for use inside a SQL string literal."""
    return "'" + value.replace("'", "''") + "'"


def build_insert_statements(posts: list[dict]) -> list[str]:
    """Turns a list of post dicts into batched INSERT statements for a
    table posts(id, user_id, title, body)."""
    statements = []
    for start in range(0, len(posts), BATCH_SIZE):
        batch = posts[start:start + BATCH_SIZE]
        value_rows = [
            f"  ({post['id']}, {post['userId']}, "
            f"{sql_string(post['title'])}, {sql_string(post['body'])})"
            for post in batch
        ]
        statement = (
            "INSERT INTO posts (id, user_id, title, body) VALUES\n"
            + ",\n".join(value_rows)
            + ";"
        )
        statements.append(statement)
    return statements


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--user-ids", type=int, nargs="+",
        help="Restrict the fetch to these user id(s) instead of all of them (useful for testing).",
    )
    args = parser.parse_args()

    user_ids = args.user_ids if args.user_ids else USER_IDS
    print(f"Fetching posts for {len(user_ids)} user id(s)...")

    posts = fetch_all(user_ids)
    print(f"Fetched {len(posts)} posts in total.")

    statements = build_insert_statements(posts)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by voorbeeld_inlezen_api.py -- example data from "
            "the JSONPlaceholder /posts API.\n\n"
        )
        f.write("\n\n".join(statements))
        f.write("\n")

    print(f"Wrote {len(statements)} INSERT statement(s) to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
